//! 定时任务与后台作业（第 21 章配套）：把「单机跑个定时器」升级成
//! 「一个集群里安全地跑定时任务」需要补齐的三块拼图。
//!
//! 集群里最大的坑：服务部署了 N 个实例，每个实例都揣着一个一模一样的调度器，
//! 同一个 tick 会被触发 **N 次**——月底对账跑 N 遍、催费邮件发 N 封、
//! 会员费扣 N 次。定时器本身没错，错在「谁来真正执行」没人拍板。
//!
//! 本示例的解法分三层，恰好对应三个模块：
//!
//! 1. [`lock`] —— **谁来干**：调度触发后先抢一把分布式锁（Redis SET NX），
//!    抢到的那一个实例才真正执行，其余的看到没抢到就跳过。这是第 15 章
//!    分布式锁在定时任务场景的直接应用。
//! 2. [`jobs`] —— **留痕与兜底**：把「这一次触发」写进数据库，靠
//!    `UNIQUE(job_name, run_key)` 兜底防重。锁是第一道防线，唯一约束是第二道
//!    （呼应第 18 章幂等）——两道防线的理由见 [`scheduler::guarded_tick`]。
//! 3. [`scheduler`] —— **怎么触发 + 怎么停**：`run_interval_job`（每隔 N 秒）
//!    与 `run_cron_job`（cron 日历规则）两种触发形态，都用
//!    `tokio_util::sync::CancellationToken` 支持优雅停机（接第 16 章）。
//!
//! 另外要记住的边界：调度器只负责「按时把活派出去」，**重活本身别在 tick 里
//! 干**。发一封邮件还好，跑一个几分钟的报表就该把任务丢进消息队列
//! （第 14 章），由后台 worker 消费——tick 只做「入队」这个轻动作，
//! 才不会因为一个慢任务拖垮整个调度循环。
//!
//! 可运行演示见 main.rs（`cargo run -p scheduler_demo`）：它在同一个进程里
//! 模拟两个逻辑实例共抢一把锁，证明 3 次触发只落 3 条记录、而非 6 条。

