//! 第 25 章配套示例库：软件许可授权（License / Activation）。
//!
//! 商业软件要防盗用、按授权范围与期限使用，主流有两条技术路线，本 crate 各给一个可跑的实现：
//!
//! - [`license`]：**离线签名授权**。厂商用私钥签发 license，客户端内置公钥离线验签，
//!   断网也能校验「谁、什么版本、开哪些功能、绑哪台机、到什么时候」。
//! - [`activation`]：**在线激活**。客户端 activate / heartbeat，厂商可远程吊销、按机器数计量。
//!
//! 对比（也见各模块头注释）：
//! - 离线 = 签名自证、可断网、不可远程撤销（只能等自然过期）；
//! - 在线 = 可远程吊销 / 计量，但依赖网络与激活服务可用性。
//!   实际产品常两者结合：离线签名保底可用，在线激活增强管控。
//!
//! 逻辑都做成可单测的纯函数 + 一个 axum oneshot 集成测试（tests/activation.rs），全内存，无外部依赖。

pub mod activation;
pub mod license;
