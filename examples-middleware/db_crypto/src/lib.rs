//! 数据库敏感字段加密存储示例（第 20 章配套）。
//!
//! ## 威胁模型：为什么手机号/身份证不能明文进库？
//!
//! 明文存储时，下面任何一条路都会直接暴露全量敏感数据：
//! - **拖库**：SQL 注入或内网横向拿到数据库访问权，一条 `SELECT *` 全带走；
//! - **备份外泄**：定时备份文件被传到对象存储/移动硬盘，权限管控往往比库本身松；
//! - **越权 SQL**：内部人员用只读账号「顺手」查同事/明星的手机号；
//! - **DBA 误操作**：排障时 `SELECT` 结果贴进工单、日志、聊天群。
//!
//! 应用层加密的目标是：**上面这些场景里流出去的都是密文**。
//!
//! ## 方案三件套（按数据的用途选工具）
//!
//! | 数据用途 | 方案 | 本仓库位置 |
//! |---|---|---|
//! | 要还原明文（展示/发短信） | 字段级可逆加密 AES-256-GCM，密文带密钥版本前缀 | [`crypto::encrypt_field`] |
//! | 要精确匹配查询（按手机号查人） | 盲索引：另存一列 HMAC-SHA256(规范化明文, 索引密钥) | [`crypto::blind_index`] |
//! | 只要验证、永不还原（密码） | 不可逆哈希 argon2 —— 第 17 章 todo_api_saas 已实现，本 crate 不重复 | — |
//!
//! ## 诚实的边界（这段比代码重要）
//!
//! - 应用层加密防的是**数据静态泄露**（拖库、备份、磁盘/快照外泄）；
//!   **不防**拿到了应用进程内密钥的攻击者——攻破应用服务器的人和应用一样能解密。
//! - 因此成败关键在**密钥管理**：本示例教学用「环境变量 + 默认值 + 显眼警告」，
//!   生产必须接 KMS。通用模式是**信封加密**（envelope encryption）：
//!   KMS 里的主密钥 KEK 从不出 KMS，只用来加解密「数据密钥 DEK」；
//!   应用启动时把 DEK 密文发给 KMS 解出明文 DEK 放内存，落盘的永远是 DEK 密文。
//!   AWS KMS 的 `GenerateDataKey`/`Decrypt`、阿里云 KMS 的信封加密 API 都是这一套。
//! - 密钥要能**轮换**：密文带 `v{n}:` 版本前缀，老数据 v1、新数据 v2 同表共存，
//!   后台任务逐步「解密→用新钥重加密」，见 [`crypto::rotate_field`] 与 [`store::rotate_all`]。
//!
//! ## 模块划分
//!
//! - [`crypto`]：纯逻辑（加解密/盲索引/轮换），不碰数据库，全部可离线单测；
//! - [`store`]：数据访问层，表结构 `dbcrypto.contacts`（密文列 + 盲索引列）；
//! - `main.rs`：可运行演示——看数据库里实际存的是什么、盲索引怎么查、轮换怎么跑。

