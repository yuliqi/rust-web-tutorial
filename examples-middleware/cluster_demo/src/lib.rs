//! 集群与分布式入门示例：单机程序长出「集群意识」需要回答两个问题——
//!
//! 1. **别人在哪？** 服务多副本部署后，实例地址是动态的（扩缩容、重启、漂移），
//!    写死 IP 行不通，需要一个「实时更新的通讯录」——这就是服务注册与发现，
//!    见 [`discovery`]（用 etcd 实现）。
//! 2. **谁来干这件事？** 多个实例同时跑定时任务、同时改同一份资源时，
//!    需要在「进程之间」互斥——单机的 Mutex 只能锁住同一个进程里的线程，
//!    跨进程/跨机器就得靠外部存储做分布式锁，见 [`dlock`]（用 Redis 实现）。
//!
//! 两个模块刻意保持独立：注册中心和分布式锁是两件事，只是常被同一类系统用到。
//! 可运行演示见 main.rs（`cargo run -p cluster_demo`）。

